const LanguageContext = createContext({
  language: "English",
  setLanguage: async () => {},
  t: (key) => STRINGS.English[key] || key,
});

function format(template, values) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    values[name] == null ? "" : String(values[name])
  );
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState("English");

  useEffect(() => {
    let active = true;
    loadAppSettings().then((prefs) => {
      if (active && prefs.language) setLanguageState(prefs.language);
    });
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = async (nextLanguage) => {
    setLanguageState(nextLanguage);
    const prefs = await loadAppSettings();
    await saveAppSettings({ ...prefs, language: nextLanguage });
  };

  const value = useMemo(() => {
    const table = STRINGS[language] || STRINGS.English;
    return {
      language,
      setLanguage,
      t: (key, values) =>
        format(table[key] || STRINGS.English[key] || key, values),
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
}

export function useI18n() {
  return useContext(LanguageContext);
}
